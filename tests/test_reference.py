class Code(UpstreamModel):
    code: str
    name: str
    rank: int


@pytest.fixture
def package(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> str:
    root = tmp_path / PKG
    (root / "reference").mkdir(parents=True)
    (root / "__init__.py").write_text("")
