"""The enum renderer of the reference frame, ``xippios.core.refresh.reference`` (ADR-0062,
decision 13): the module ``enums.py`` that the frame renders from the packaged lists.

The renderer stands in the frame's module, the one that calls it, and the run-time module
``xippios.core.reference`` keeps none of it: its tests moved here with it, unchanged.
"""

import subprocess
