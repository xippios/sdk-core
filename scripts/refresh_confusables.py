"""Regenerate ``src/xippios/core/_confusables.py`` from the installed ruff.

Ruff flags a confusable character in a string (RUF001), a docstring (RUF002) and a comment
(RUF003) from one table. This script asks the installed ruff, with its defaults and preview
off, which non-ASCII code points it flags in the string ``"a<c>"``: a word with an ASCII
letter in it makes every confusable count, letters as well as punctuation and spaces. The
module it writes lists them as hexadecimal ranges for ``xippios.core.reference``, which
writes each of them as a Unicode escape. Run it from the repository root after a ruff
upgrade::

    uv run python scripts/refresh_confusables.py            # rewrite the module
    uv run python scripts/refresh_confusables.py --check    # exit 1 if it is stale
"""

import argparse
import json
import subprocess
import sys
import tempfile
import textwrap
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULE = ROOT / "src/xippios/core/_confusables.py"
CODE_POINTS = [code for code in range(0x80, 0x110000) if not 0xD800 <= code <= 0xDFFF]
"""Every non-ASCII code point a Python source file can hold."""
PROBE_COLUMN = 7
"""Where ``c`` sits in the probe line ``X = "a<c>"``, counted from 1 as ruff counts."""


def ruff(*args: str) -> subprocess.CompletedProcess[str]:
    """The installed ruff, run with ``args``."""
    command = [sys.executable, "-m", "ruff", *args]
    return subprocess.run(command, capture_output=True, text=True, check=False)


def probe() -> list[int]:
    """Every non-ASCII code point ruff flags as confusable, in order.

    One probe line per code point, so a finding's row names its code point; a finding at
    any other column, or of any other rule, stops the script.
    """
    lines = [f'X = "a{chr(code)}"' for code in CODE_POINTS]
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "probe.py"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        args = ("--no-cache", "--isolated", "--select", "RUF001", "--output-format", "json")
        result = ruff("check", *args, str(path))
    findings = json.loads(result.stdout)
    for finding in findings:
        if finding["code"] != "RUF001" or finding["location"]["column"] != PROBE_COLUMN:
            raise SystemExit(f"unexpected finding: {finding['code']} at {finding['location']}")
    return sorted(CODE_POINTS[finding["location"]["row"] - 1] for finding in findings)


def spans(codes: Sequence[int]) -> list[str]:
    """``codes`` as hexadecimal ranges: ``a0``, ``2000-200a``."""
    runs: list[list[int]] = []
    for code in codes:
        if runs and code == runs[-1][1] + 1:
            runs[-1][1] = code
        else:
            runs.append([code, code])
    return [f"{first:x}" if first == last else f"{first:x}-{last:x}" for first, last in runs]


def render(codes: Sequence[int], version: str) -> str:
    """The module's source for ``codes``, probed from ruff ``version``."""
    table = textwrap.fill(" ".join(spans(codes)), width=96)
    return f'''"""Characters ruff flags as confusable: in a string, a docstring or a comment.

Generated by ``scripts/refresh_confusables.py`` from ruff {version}, preview off; do not edit by
hand. RUF001, RUF002 and RUF003 share the table. {len(codes)} code points, as hexadecimal ranges.
"""

__all__ = ["CONFUSABLES"]

_SPANS = """
{table}
"""


def _expand(span: str) -> range:
    first, _, last = span.partition("-")
    return range(int(first, 16), int(last or first, 16) + 1)


CONFUSABLES = frozenset(code for span in _SPANS.split() for code in _expand(span))
"""Code points ruff calls confusable, all of them outside ASCII."""
'''


def main(argv: Sequence[str] | None = None) -> None:
    """Probe the installed ruff and write the module, or with ``--check`` compare it."""
    summary, _, details = (__doc__ or "").partition("\n\n")
    parser = argparse.ArgumentParser(
        prog="refresh_confusables.py",
        description=summary,
        epilog=details,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--check", action="store_true", help="exit 1 if the module is stale")
    check = parser.parse_args(argv).check
    version = ruff("--version").stdout.split()[-1]
    source = render(probe(), version)
    if check:
        if MODULE.read_text(encoding="utf-8") != source:
            raise SystemExit(f"{MODULE.relative_to(ROOT)} is stale; run without --check")
        return
    MODULE.write_text(source, encoding="utf-8")
    sys.stdout.write(f"{MODULE.relative_to(ROOT)} written from ruff {version}\n")


if __name__ == "__main__":
    main()
